/**
 * Turns province boundaries into static SVG path strings for the goal map.
 *
 *   apps/web/data/tr-provinces.geo.json  ──▶  src/components/turkey-map/paths.generated.ts
 *
 * Run with `pnpm --filter @mentor/web build:map` and commit the output. NOT part of `next build`:
 * the boundaries change about never, and this keeps d3-geo out of the runtime bundle entirely —
 * the app ships plain strings, no projection code, no map library.
 *
 * Usage: pnpm --filter @mentor/web build:map
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";
import { geoMercator, geoPath } from "d3-geo";

const HERE = dirname(fileURLToPath(import.meta.url));
const INPUT = resolve(HERE, "../data/tr-provinces.geo.json");
/** Single source of truth for the 81 slugs — the same file the API seeds `cities` from. */
const CITIES = resolve(
  HERE,
  "../../api/src/modules/content/seed/cities.seed.json",
);
const OUTPUT = resolve(HERE, "../src/components/turkey-map/paths.generated.ts");

const WIDTH = 1000;
const HEIGHT = 420;

/**
 * Province names the source spells differently from the seed. Extend as needed — the script fails
 * loudly on any unmatched feature rather than silently dropping a province off the map.
 */
const NAME_ALIASES = {
  afyon: "afyonkarahisar",
  icel: "mersin",
  kmaras: "kahramanmaras",
  maras: "kahramanmaras",
  urfa: "sanliurfa",
  antep: "gaziantep",
};

/**
 * Centroid overrides for provinces whose polygon is concave enough that the computed centroid
 * lands outside it (the badge would float in the sea or in a neighbouring province).
 * Values are in the projected 1000x420 viewBox. Fill in whatever the assert below reports.
 */
const CENTROID_OVERRIDES = {};

const TR_MAP = { ç: "c", ğ: "g", ı: "i", İ: "i", ö: "o", ş: "s", ü: "u", â: "a", î: "i", û: "u" };

/**
 * Turkish-aware slug. `toLowerCase()` alone is not enough: "İ" lowercases to a dotted "i̇" (i + U+0307)
 * in JS, so İstanbul would slug to "i̇stanbul" and never match "istanbul".
 */
function slugify(name) {
  return [...String(name)]
    .map((ch) => TR_MAP[ch] ?? ch)
    .join("")
    .toLowerCase()
    .replace(/[^a-z]/g, "");
}

function featureName(feature) {
  const p = feature.properties ?? {};
  return p.name ?? p.NAME ?? p.name_tr ?? p.NAME_1 ?? p.province ?? p.il ?? "";
}

function main() {
  const raw = JSON.parse(readFileSync(INPUT, "utf8"));
  assert(
    !raw.objects,
    `${INPUT} looks like TopoJSON (it has .objects). Convert it to GeoJSON first — this script takes GeoJSON so it needs only d3-geo.`,
  );
  const features = raw.type === "FeatureCollection" ? raw.features : [raw];

  const { cities } = JSON.parse(readFileSync(CITIES, "utf8"));
  const codeBySlug = new Map(cities.map((c) => [c.slug, c.code]));

  const projection = geoMercator().fitSize([WIDTH, HEIGHT], {
    type: "FeatureCollection",
    features,
  });
  const path = geoPath(projection);

  const provinces = {};
  const unmatched = [];

  for (const feature of features) {
    const name = featureName(feature);
    const slug = slugify(name);
    const code = codeBySlug.get(NAME_ALIASES[slug] ?? slug);
    if (!code) {
      unmatched.push(name || "(unnamed feature)");
      continue;
    }

    // One decimal is ~40m on this projection — invisible on screen, and it cuts the path payload
    // by roughly 60%. Cheaper and simpler than pulling in a topology-simplification pass.
    const d = path(feature).replace(/\d+\.\d+/g, (n) => Number(n).toFixed(1));
    const [cx, cy] = CENTROID_OVERRIDES[code] ?? path.centroid(feature);

    provinces[code] = {
      d,
      cx: Number(cx.toFixed(1)),
      cy: Number(cy.toFixed(1)),
    };
  }

  assert.deepEqual(
    unmatched,
    [],
    `Unmatched provinces — add them to NAME_ALIASES: ${unmatched.join(", ")}`,
  );

  const codes = Object.keys(provinces).sort();
  assert.equal(codes.length, 81, `Expected 81 provinces, produced ${codes.length}`);

  for (const code of codes) {
    const p = provinces[code];
    assert(
      p.d.startsWith("M") && p.d.length > 20,
      `Province ${code} produced a degenerate path (${p.d.length} chars)`,
    );
    assert(
      p.cx > 0 && p.cx < WIDTH && p.cy > 0 && p.cy < HEIGHT,
      `Province ${code} centroid (${p.cx}, ${p.cy}) fell outside the viewBox — add a CENTROID_OVERRIDES entry`,
    );
  }

  const body = codes
    .map((code) => {
      const p = provinces[code];
      return `  "${code}": { d: "${p.d}", cx: ${p.cx}, cy: ${p.cy} },`;
    })
    .join("\n");

  writeFileSync(
    OUTPUT,
    `// AUTO-GENERATED by scripts/build-turkey-map.mjs — do not edit by hand.
// Regenerate with: pnpm --filter @mentor/web build:map
// Boundary data © OpenStreetMap contributors, ODbL.

export interface ProvinceShape {
  /** SVG path data in the ${WIDTH}x${HEIGHT} viewBox. */
  d: string;
  /** Projected centroid — where the university badge sits. */
  cx: number;
  cy: number;
}

export const MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

/** Keyed by plate code "01".."81", matching \`cities.code\` in the API. */
export const PROVINCES: Record<string, ProvinceShape> = {
${body}
};
`,
    "utf8",
  );

  const bytes = Buffer.byteLength(body, "utf8");
  console.log(
    `${codes.length} provinces → ${OUTPUT} (${(bytes / 1024).toFixed(1)} KB of path data)`,
  );
}

main();
