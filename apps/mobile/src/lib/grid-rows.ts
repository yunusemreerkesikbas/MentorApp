/** Splits grid cards into rows of `size`; the last row is padded with nulls so cards keep one width. */
export function gridRows<T>(items: readonly T[], size: number): (T | null)[][] {
  const rows: (T | null)[][] = [];
  for (let i = 0; i < items.length; i += size) {
    const row: (T | null)[] = items.slice(i, i + size);
    while (row.length < size) row.push(null);
    rows.push(row);
  }
  return rows;
}
